import { getStructuredModel } from '@/lib/ai/gemini';
import { generateStructured } from '@/lib/ai/structured';
import { MentorRecommendationSchema, type MentorRecommendation } from '@/lib/validation/schemas';
import { buildMentorSystemPrompt } from '@/prompts/mentor';
import type { PreferredLanguage } from '@/prompts/language';
import type { PerformanceBreakdown } from './performance-agent';

export interface MentorAgentInput {
  performance: PerformanceBreakdown;
  learnerContext: string[];
  /** Feature 6: the student's own recent questions to the Tutor, most recent first. */
  recentTutorQuestions: string[];
  mentorDisplayName: string;
  language?: PreferredLanguage;
}

const RESPONSE_SCHEMA_DESCRIPTION = `{
  "summary": string,
  "recommendations": [ { "topic": string, "reason": string, "action": string } ]
}`;

/**
 * MENTOR_AGENT — internal id: MENTOR_AGENT.
 * Pure function: (performance breakdown, learner memory) -> validated
 * recommendation. A YouTube search link per weak topic is attached by the
 * API route afterwards (deterministically built from the topic string),
 * never generated by the model — an LLM has no way to know a real, current
 * video exists at a URL it writes down, so we never ask it to produce one.
 */
export async function runMentorAgent(input: MentorAgentInput): Promise<MentorRecommendation> {
  if (!input.performance.hasData) {
    return {
      summary:
        "You haven't completed an assessment yet, so there's no performance data to analyse. Take a quick test on a topic you've studied to get your first personalised recommendation.",
      recommendations: [
        {
          topic: 'Any studied topic',
          reason: 'No assessment attempts recorded yet.',
          action: 'Open a topic you\u2019ve generated notes for and take its assessment.',
        },
      ],
    };
  }

  const model = getStructuredModel({ temperature: 0.4, maxOutputTokens: 2048 });

  const contextBlock =
    input.learnerContext.length > 0
      ? `\n\nRELEVANT LEARNING MEMORY:\n- ${input.learnerContext.join('\n- ')}`
      : '';

  const tutorQuestionsBlock =
    input.recentTutorQuestions.length > 0
      ? `\n\nRECENT QUESTIONS THE STUDENT ASKED THE TUTOR (most recent first — use these to notice what they're currently curious or confused about, alongside the performance data; don't just repeat performance data using different words):\n- ${input.recentTutorQuestions.join('\n- ')}`
      : '';

  const instruction = `Here is the student's computed performance breakdown:

Strong concepts: ${input.performance.strong.join(', ') || '(none)'}
Moderate concepts: ${input.performance.moderate.join(', ') || '(none)'}
Weak concepts: ${input.performance.weak.join(', ') || '(none)'}${contextBlock}${tutorQuestionsBlock}

Return a JSON object matching exactly this shape:
${RESPONSE_SCHEMA_DESCRIPTION}`;

  return generateStructured(model, MentorRecommendationSchema, [
    ['system', buildMentorSystemPrompt(input.mentorDisplayName, input.language)],
    ['user', instruction],
  ]);
}
